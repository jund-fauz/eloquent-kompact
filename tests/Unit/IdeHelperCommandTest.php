<?php

namespace JundFauz\EloquentKompact\Tests\Unit;

use JundFauz\EloquentKompact\Console\IdeHelperCommand;
use JundFauz\EloquentKompact\Tests\TestCase;
use PHPUnit\Framework\Attributes\Test;

class IdeHelperCommandTest extends TestCase
{
    private function invoke(string $method, mixed ...$arguments): mixed
    {
        return (fn () => $this->{$method}(...$arguments))->call(new IdeHelperCommand);
    }

    #[Test]
    public function it_prefixes_the_mixin_class_inside_the_mixin_namespace(): void
    {
        $this->assertSame('EloquentKompact\IdeHelper\App\Models\_EK_User', $this->invoke('mixinFqn', 'App\Models\User'));
        $this->assertSame('EloquentKompact\IdeHelper\App\Models\Shop\_EK_Product', $this->invoke('mixinFqn', 'App\Models\Shop\Product'));
    }

    #[Test]
    public function it_renders_a_mixin_block(): void
    {
        $block = $this->invoke('renderMixin', 'App\Models\Post', [
            'authorUser' => ['type' => 'belongsTo', 'class' => 'App\Models\User'],
            'comments' => ['type' => 'hasMany', 'class' => 'App\Models\Comment'],
        ]);

        $this->assertSame(implode("\n", [
            'namespace EloquentKompact\IdeHelper\App\Models {',
            '    /**',
            '     * @property-read \App\Models\User|null $authorUser',
            '     * @method \Illuminate\Database\Eloquent\Relations\BelongsTo<\App\Models\User, \App\Models\Post> authorUser()',
            '     * @property-read \Illuminate\Database\Eloquent\Collection<int, \App\Models\Comment> $comments',
            '     * @method \Illuminate\Database\Eloquent\Relations\HasMany<\App\Models\Comment, \App\Models\Post> comments()',
            '     */',
            '    class _EK_Post {}',
            '}',
        ]), $block);
    }

    #[Test]
    public function it_renders_singular_relations_as_nullable_models(): void
    {
        $block = $this->invoke('renderMixin', 'App\Models\User', [
            'profile' => ['type' => 'hasOne', 'class' => 'App\Models\Profile'],
        ]);

        $this->assertStringContainsString('@property-read \App\Models\Profile|null $profile', $block);
        $this->assertStringContainsString('@method \Illuminate\Database\Eloquent\Relations\HasOne<\App\Models\Profile, \App\Models\User> profile()', $block);
    }

    #[Test]
    public function it_renders_the_file_header(): void
    {
        $this->assertSame(implode("\n", [
            '<?php',
            '/** @noinspection all */',
            '',
            '// @formatter:off',
            '// phpcs:ignoreFile',
            "// Generated by `php artisan kompact:ide-helper`, don't edit manually.",
            '',
            'BLOCK',
            '',
        ]), $this->invoke('renderFile', ['BLOCK']));
    }
}
