<?php

namespace JundFauz\EloquentKompact\Tests\Unit;

use Illuminate\Database\Events\MigrationsEnded;
use Illuminate\Database\Schema\Blueprint;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Schema;
use JundFauz\EloquentKompact\Column\Builder\Concerns\ColumnBuilder;
use JundFauz\EloquentKompact\Column\Builder\Concerns\Morph;
use JundFauz\EloquentKompact\Column\ColumnListing;
use JundFauz\EloquentKompact\Console\ColumnBuilderCommand;
use JundFauz\EloquentKompact\Tests\TestCase;
use PHPUnit\Framework\Attributes\Test;

class ColumnBuilderCommandTest extends TestCase
{
    private string $appPath;
    private string $tempPath;

    protected function setUp(): void
    {
        parent::setUp();

        ColumnListing::flush();
        Schema::create('cb_orders', function (Blueprint $table) {
            $table->id();
            $table->foreignId('customer_user_id');
            $table->string('status_enum');
            $table->decimal('net_weight_gram');
            $table->decimal('tax_percentage');
            $table->boolean('paid_is');
            $table->json('tags_array');
            $table->string('price_pu');
            $table->morphs('sourceable');
            $table->timestamps();
        });
        Schema::create('cb_items', function (Blueprint $table) {
            $table->id();
            $table->decimal('net_weight_gram');
            $table->time('start_time');
            $table->string('note_type');
        });

        config(['eloquent-kompact.column.custom_tokens' => ['per_unit' => ['pu', 'decimal:3']]]);

        $this->appPath = $this->app->path();
        $this->tempPath = sys_get_temp_dir() . DIRECTORY_SEPARATOR . 'kompact-column-builder-' . uniqid();
        $this->app->useAppPath($this->tempPath);
    }

    protected function tearDown(): void
    {
        File::deleteDirectory($this->tempPath);
        $this->app['env'] = 'testing';
        $this->app->useAppPath($this->appPath);
        ColumnListing::flush();

        parent::tearDown();
    }

    private function file(string $class): string
    {
        return File::get($this->tempPath . '/Constant/Column/' . $class . '.php');
    }

    #[Test]
    public function it_generates_a_class_for_every_token_but_the_relation(): void
    {
        $this->artisan('kompact:column-builder', ['-o' => 'App\Constant\Column'])->assertSuccessful();

        $files = collect(File::files($this->tempPath . '/Constant/Column'))->map->getFilename()->sort()->values()->all();

        $this->assertSame([
            'ArrayC.php', 'Boolean.php', 'Dropdown.php', 'Enum.php', 'Gram.php', 'Morph.php', 'Pcs.php',
            'PerUnit.php', 'Percentage.php', 'Time.php', 'Timestamp.php', 'Type.php',
        ], $files);
    }

    #[Test]
    public function it_lists_the_columns_of_the_database_as_methods(): void
    {
        $this->artisan('kompact:column-builder', ['--output' => 'App\Constant\Column'])->assertSuccessful();

        $this->assertSame(<<<'PHP'
            <?php

            namespace App\Constant\Column;

            use JundFauz\EloquentKompact\Column\Builder\Concerns\ColumnBuilder;

            /**
             * Generated by `php artisan kompact:column-builder`, run it again after changing the database.
             *
             * @method static string netWeight()
             */
            class Gram extends ColumnBuilder {}

            PHP, $this->file('Gram'));
        $this->assertStringContainsString('@method static string created()', $this->file('Timestamp'));
        $this->assertStringContainsString('@method static string updated()', $this->file('Timestamp'));
        $this->assertStringContainsString('@method static string price()', $this->file('PerUnit'));
        $this->assertStringContainsString('class ArrayC extends ColumnBuilder', $this->file('ArrayC'));
        $this->assertStringNotContainsString('@method', $this->file('Dropdown'));
        $this->assertStringContainsString('Generated by', $this->file('Dropdown'));
    }

    #[Test]
    public function it_generates_the_morph_class_with_its_morph_names(): void
    {
        $this->artisan('kompact:column-builder', ['-o' => 'App\Constant\Column'])->assertSuccessful();

        $this->assertSame(<<<'PHP'
            <?php

            namespace App\Constant\Column;

            use JundFauz\EloquentKompact\Column\Builder\Concerns\Morph as BaseMorph;

            /**
             * Generated by `php artisan kompact:column-builder`, run it again after changing the database.
             *
             * @method static string sourceableId()
             * @method static string sourceableModel()
             */
            class Morph extends BaseMorph
            {
                public const string sourceable = 'sourceable';
            }

            PHP, $this->file('Morph'));
    }

    #[Test]
    public function the_generated_classes_build_the_column_names(): void
    {
        $this->artisan('kompact:column-builder', ['-o' => 'App\Generated\Columns'])->assertSuccessful();

        foreach (['ArrayC', 'Gram', 'PerUnit', 'Morph'] as $class) {
            require_once $this->tempPath . "/Generated/Columns/$class.php";
        }

        $this->assertTrue(is_subclass_of(\App\Generated\Columns\Gram::class, ColumnBuilder::class));
        $this->assertSame('net_weight_gram', \App\Generated\Columns\Gram::netWeight());
        $this->assertSame('tags_array', \App\Generated\Columns\ArrayC::tags());
        $this->assertSame('price_pu', \App\Generated\Columns\PerUnit::price());
        $this->assertTrue(is_subclass_of(\App\Generated\Columns\Morph::class, Morph::class));
        $this->assertSame('sourceable_id', \App\Generated\Columns\Morph::sourceableId());
        $this->assertSame('sourceable_type', \App\Generated\Columns\Morph::sourceableModel());
    }

    #[Test]
    public function it_asks_the_output_when_it_is_not_given(): void
    {
        $this->artisan('kompact:column-builder')
            ->expectsQuestion('Namespace of the column builder classes, inside app/', 'App\Asked')
            ->assertSuccessful();

        $this->assertFileExists($this->tempPath . '/Asked/Gram.php');
    }

    #[Test]
    public function it_updates_its_classes_to_the_latest_database_when_run_again(): void
    {
        $this->artisan('kompact:column-builder', ['-o' => 'App\Constant\Column'])->assertSuccessful();

        // A renamed constant of Morph is kept
        File::put(
            $this->tempPath . '/Constant/Column/Morph.php',
            str_replace("const string sourceable = 'sourceable'", "const string source = 'sourceable'", $this->file('Morph')),
        );

        Schema::table('cb_items', function (Blueprint $table) {
            $table->decimal('gross_weight_gram')->nullable();
            $table->nullableMorphs('parentable');
        });

        $this->artisan('kompact:column-builder', ['-o' => 'App\Constant\Column'])
            ->expectsOutputToContain('Updated App\Constant\Column\Gram')
            ->assertSuccessful();

        $this->assertStringContainsString("@method static string grossWeight()
 * @method static string netWeight()", $this->file('Gram'));
        $this->assertStringContainsString("public const string parentable = 'parentable';", $this->file('Morph'));
        $this->assertStringContainsString("public const string source = 'sourceable';", $this->file('Morph'));
        $this->assertStringContainsString('@method static string sourceId()', $this->file('Morph'));
        $this->assertStringNotContainsString('sourceableId()', $this->file('Morph'));
    }

    #[Test]
    public function it_drops_the_columns_that_are_gone(): void
    {
        $this->artisan('kompact:column-builder', ['-o' => 'App\Constant\Column'])->assertSuccessful();

        Schema::drop('cb_items');
        Schema::table('cb_orders', fn (Blueprint $table) => $table->dropMorphs('sourceable'));

        $this->artisan('kompact:column-builder', ['-o' => 'App\Constant\Column'])->assertSuccessful();

        $this->assertStringNotContainsString('start()', $this->file('Time'));
        $this->assertStringNotContainsString('sourceable', $this->file('Morph'));
        $this->assertStringContainsString('class Morph extends BaseMorph {}', $this->file('Morph'));
    }

    #[Test]
    public function it_keeps_the_classes_it_did_not_generate_unless_forced(): void
    {
        File::ensureDirectoryExists($this->tempPath . '/Constant/Column');
        File::put($this->tempPath . '/Constant/Column/Gram.php', 'mine');

        $this->artisan('kompact:column-builder', ['-o' => 'App\Constant\Column'])
            ->expectsOutputToContain('Skipped App\Constant\Column\Gram')
            ->assertSuccessful();
        $this->assertSame('mine', $this->file('Gram'));

        $this->artisan('kompact:column-builder', ['-o' => 'App\Constant\Column', '--force' => true])->assertSuccessful();
        $this->assertStringContainsString('class Gram extends ColumnBuilder', $this->file('Gram'));
    }

    #[Test]
    public function it_finds_the_namespaces_it_generated_before(): void
    {
        $this->assertSame([], ColumnBuilderCommand::generatedNamespaces());

        $this->artisan('kompact:column-builder', ['-o' => 'App\Constant\Column'])->assertSuccessful();
        $this->artisan('kompact:column-builder', ['-o' => 'App\Generated\Columns'])->assertSuccessful();
        File::put($this->tempPath . '/Mine.php', "<?php

namespace App;

class Mine {}
");

        $this->assertSame(['App\Constant\Column', 'App\Generated\Columns'], ColumnBuilderCommand::generatedNamespaces());
    }

    #[Test]
    public function it_regenerates_its_classes_after_migrating_locally(): void
    {
        $this->artisan('kompact:column-builder', ['-o' => 'App\Constant\Column'])->assertSuccessful();

        Schema::table('cb_items', fn (Blueprint $table) => $table->decimal('gross_weight_gram')->nullable());
        $this->app['env'] = 'local';
        event(new MigrationsEnded('up'));

        $this->assertStringContainsString('@method static string grossWeight()', $this->file('Gram'));
    }

    #[Test]
    public function it_does_not_regenerate_its_classes_after_migrating_outside_local(): void
    {
        $this->artisan('kompact:column-builder', ['-o' => 'App\Constant\Column'])->assertSuccessful();

        Schema::table('cb_items', fn (Blueprint $table) => $table->decimal('gross_weight_gram')->nullable());
        event(new MigrationsEnded('up'));

        $this->assertStringNotContainsString('grossWeight()', $this->file('Gram'));
    }

    #[Test]
    public function it_generates_nothing_after_migrating_when_it_never_ran(): void
    {
        $this->app['env'] = 'local';
        event(new MigrationsEnded('up'));

        $this->assertDirectoryDoesNotExist($this->tempPath);
    }
}
