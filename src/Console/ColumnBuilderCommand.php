<?php

namespace JundFauz\EloquentKompact\Console;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Schema;
use JundFauz\EloquentKompact\Builder\Str;
use JundFauz\EloquentKompact\Column\Builder\Concerns\ColumnBuilder;
use JundFauz\EloquentKompact\Column\Builder\Concerns\Morph;
use JundFauz\EloquentKompact\Column\ColumnCheck;
use JundFauz\EloquentKompact\Column\ColumnCreator;
use JundFauz\EloquentKompact\Column\ColumnListing;
use ReflectionClass;
use ReflectionClassConstant;
use Symfony\Component\Finder\Finder;
use Symfony\Component\Finder\SplFileInfo;
use Throwable;
use function JundFauz\EloquentKompact\full_path_on_app;
use function JundFauz\EloquentKompact\is_not_dir;
use function JundFauz\EloquentKompact\namespace_concat;
use function JundFauz\EloquentKompact\path_concat;

final class ColumnBuilderCommand extends Command
{
    protected $signature = 'kompact:column-builder
        {--o|output= : Namespace of the classes inside app/, e.g. App\Constant\Column (asked when not given)}
        {--force : Also overwrite the classes that were not generated by this command}';

    protected $description = 'Generate a column builder class for every column token, with the columns of the database as its methods';

    public const string DefaultOutput = 'App\Constant\Column';

    /** Marks a class generated by this command, so a later run updates it. */
    protected const string Marker = 'Generated by `php artisan kompact:column-builder`';

    /** Tokens without a column builder class. */
    protected const array Skipped = ['Relation'];

    /** Names that cannot be a class name, so their class gets a `C` at the end, like `ArrayC`. */
    protected const array Reserved = [
        'abstract', 'and', 'array', 'as', 'bool', 'break', 'callable', 'case', 'catch', 'class', 'clone', 'const',
        'continue', 'declare', 'default', 'do', 'echo', 'else', 'elseif', 'empty', 'enddeclare', 'endfor',
        'endforeach', 'endif', 'endswitch', 'endwhile', 'eval', 'exit', 'extends', 'false', 'final', 'finally',
        'float', 'fn', 'for', 'foreach', 'function', 'global', 'goto', 'if', 'implements', 'include', 'instanceof',
        'insteadof', 'int', 'interface', 'isset', 'iterable', 'list', 'match', 'mixed', 'namespace', 'never', 'new',
        'null', 'object', 'or', 'parent', 'print', 'private', 'protected', 'public', 'readonly', 'require', 'return',
        'self', 'static', 'string', 'switch', 'throw', 'trait', 'true', 'try', 'unset', 'use', 'var', 'void',
        'while', 'xor', 'yield',
    ];

    public function handle(): int
    {
        $namespace = trim(
            $this->option('output') ?: $this->ask('Namespace of the column builder classes, inside app/', self::DefaultOutput),
            '\\/'
        );
        $directory = full_path_on_app($namespace);
        $columns = $this->columns();

        File::ensureDirectoryExists($directory);

        foreach ($this->classes() as $token => $class) {
            $methods = $columns->filter(fn (string $column) => ColumnCreator::getColumnType($column) === $token)
                ->map(fn (string $column) => ColumnCreator::getPlainColumnName($column)->camel()->value())
                ->unique()
                ->sort()
                ->map(fn (string $method) => "$method()")
                ->all();

            $this->write($directory, $namespace, $class, $this->builderClass($namespace, $class, $methods));
        }

        $morphs = $columns->filter(fn (string $column) => ColumnCheck::isType($column))
            ->map(fn (string $column) => ColumnCreator::getPlainColumnName($column)->value())
            ->filter(fn (string $morph) => $columns->contains(ColumnCreator::relation($morph)))
            ->unique()
            ->sort()
            ->values()
            ->all();

        $this->write($directory, $namespace, 'Morph', $this->morphClass($namespace, $morphs, $this->morphNames($directory)));

        return self::SUCCESS;
    }

    /**
     * Namespaces of the classes this command generated before inside app/, read from their `namespace` line.
     *
     * @return array<int, string>
     */
    public static function generatedNamespaces(): array
    {
        if (is_not_dir(app_path())) {
            return [];
        }

        return collect(Finder::create()->files()->in(app_path())->name('*.php')->contains(self::Marker))
            ->map(fn (SplFileInfo $file) => preg_match('/^namespace\s+([^;\s]+)\s*;/m', $file->getContents(), $match) ? $match[1] : null)
            ->filter()
            ->unique()
            ->sort()
            ->values()
            ->all();
    }

    /**
     * Token => class name, for the built-in tokens and the custom tokens of the config.
     *
     * @return array<string, string>
     */
    protected function classes(): array
    {
        $classes = [];

        foreach ((new ReflectionClass(ColumnCreator::class))->getReflectionConstants(ReflectionClassConstant::IS_PUBLIC) as $constant) {
            if (is_string($constant->getValue()) && ! in_array($constant->getName(), self::Skipped, true)) {
                $classes[$constant->getValue()] = $this->className($constant->getName());
            }
        }

        foreach (config('eloquent-kompact.column.custom_tokens') ?? [] as $name => $definition) {
            [$token] = (array) $definition;
            $classes[$token] = $this->className(Str::of($name)->pascal()->value());
        }

        return $classes;
    }

    protected function className(string $name): string
    {
        return in_array(strtolower($name), self::Reserved, true) ? "{$name}C" : $name;
    }

    /**
     * Every column of every table, or none when the database cannot be read.
     *
     * @return \Illuminate\Support\Collection<int, string>
     */
    protected function columns(): \Illuminate\Support\Collection
    {
        try {
            // The latest columns, not the cached ones, e.g. after the schema changed without a migration.
            ColumnListing::flush();

            return collect(Schema::getTableListing(schemaQualified: false))
                ->flatMap(fn (string $table) => ColumnListing::of($table))
                ->unique()
                ->values();
        } catch (Throwable $exception) {
            $this->warn("The database cannot be read, so the classes have no methods: {$exception->getMessage()}");

            return collect();
        }
    }

    /**
     * @param  array<int, string>  $methods
     */
    protected function builderClass(string $namespace, string $class, array $methods): string
    {
        $parent = class_basename(ColumnBuilder::class);

        return $this->php($namespace, ColumnBuilder::class, $this->docblock($methods) . "class $class extends $parent {}");
    }

    /**
     * Morph name => constant name, of the Morph class generated before, so a renamed constant is kept.
     *
     * @return array<string, string>
     */
    protected function morphNames(string $directory): array
    {
        $file = path_concat($directory, 'Morph.php');

        if (! File::exists($file)) {
            return [];
        }

        preg_match_all("/const\s+(?:string\s+)?(\w+)\s*=\s*'([^']+)'/", File::get($file), $matches, PREG_SET_ORDER);

        return collect($matches)->mapWithKeys(fn (array $match) => [$match[2] => $match[1]])->all();
    }

    /**
     * @param  array<int, string>  $morphs
     * @param  array<string, string>  $names  Morph name => constant name
     */
    protected function morphClass(string $namespace, array $morphs, array $names = []): string
    {
        $methods = [];
        $constants = [];

        foreach ($morphs as $morph) {
            $name = $names[$morph] ?? Str::of($morph)->camel()->value();
            $methods[] = "{$name}Id()";
            $methods[] = "{$name}Model()";
            $constants[] = "    public const string $name = '$morph';";
        }

        $body = $constants === [] ? ' {}' : "\n{\n" . implode("\n\n", $constants) . "\n}";

        return $this->php($namespace, Morph::class . ' as BaseMorph', $this->docblock($methods) . "class Morph extends BaseMorph$body");
    }

    /**
     * @param  array<int, string>  $methods
     */
    protected function docblock(array $methods): string
    {
        $lines = [' * ' . self::Marker . ', run it again after changing the database.'];

        if ($methods !== []) {
            $lines[] = ' *';
            foreach ($methods as $method) {
                $lines[] = " * @method static string $method";
            }
        }

        return "/**\n" . implode("\n", $lines) . "\n */\n";
    }

    protected function php(string $namespace, string $use, string $class): string
    {
        return "<?php\n\nnamespace $namespace;\n\nuse $use;\n\n$class\n";
    }

    protected function write(string $directory, string $namespace, string $class, string $content): void
    {
        $file = path_concat($directory, "$class.php");
        $name = namespace_concat($namespace, $class);

        $exists = File::exists($file);

        if ($exists && ! $this->option('force') && ! str_contains(File::get($file), self::Marker)) {
            $this->line("Skipped $name, it was not generated by this command (use --force to overwrite it)");

            return;
        }

        File::put($file, $content);
        $this->info(($exists ? 'Updated ' : 'Generated ') . $name);
    }
}
